/** Generate the desktop fallback catalog without importing browser source from a packaged app. */
import {writeFile} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {automationTools} from '../app/editor-automation.mjs';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
export async function generateMcpSchemas(sourceRoot=root) {
  const schemas=Object.fromEntries(automationTools({}).map(tool=>[tool.name,tool.inputSchema]));
  await writeFile(resolve(sourceRoot,'desktop/mcp-schemas.mjs'),'// Generated by scripts/generate-mcp-schemas.mjs. Do not edit by hand.\nexport default '+JSON.stringify(schemas,null,2)+';\n');
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href)await generateMcpSchemas();
